const enc = new TextEncoder();

async function sha256(s: string): Promise<string> {
  const d = new Uint8Array(
    await crypto.subtle.digest("SHA-256", enc.encode(s)),
  );
  return [...d].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** The one formatter for both sides. ponytail: no AL formatter exists; whitespace only. */
export function formatText(s: string): string {
  return s.replaceAll("\r\n", "\n").replaceAll("\r", "\n").replaceAll(
    "\t",
    "    ",
  ).split("\n").map((l) => l.trimEnd()).join("\n");
}

export interface PairKey {
  task: string;
  repeat: number;
  baseline: string;
  variant: string;
}
export const pairKey = (p: PairKey) =>
  `${p.task}|${p.repeat}|${p.baseline}|${p.variant}`;

/**
 * Balanced A/B within each task: its pairs sorted by a seeded hash, then
 * baseline-is-A alternates down the list from a seeded start. Counts differ by
 * at most one per task.
 */
export async function assignBalanced(
  seed: string,
  pairs: PairKey[],
): Promise<Map<string, boolean>> {
  const out = new Map<string, boolean>();
  const byTask = new Map<string, PairKey[]>();
  for (const p of pairs) byTask.set(p.task, [...byTask.get(p.task) ?? [], p]);
  for (const [task, list] of byTask) {
    const hashed = await Promise.all(list.map(async (p) => ({
      p,
      h: await sha256(
        `${seed}|${p.task}|${p.repeat}|${p.baseline}|${p.variant}`,
      ),
    })));
    hashed.sort((x, y) => x.h.localeCompare(y.h));
    const start = parseInt((await sha256(`${seed}|${task}`)).slice(0, 2), 16) %
        2 === 0;
    hashed.forEach(({ p }, k) => out.set(pairKey(p), (k % 2 === 0) === start));
  }
  return out;
}

export function extractRubric(text: string): string {
  const a = text.indexOf("<!-- judge:start -->");
  const b = text.indexOf("<!-- judge:end -->");
  if (a < 0 || b < 0 || b < a) {
    throw new Error("rubric: judge:start / judge:end markers missing");
  }
  return text.slice(a + "<!-- judge:start -->".length, b).trim();
}

export function fillTemplate(
  template: string,
  rubric: string,
  taskPrompt: string,
  sideA: string,
  sideB: string,
): string {
  const vals: Record<string, string> = {
    RUBRIC: rubric,
    TASK_PROMPT: taskPrompt,
    SIDE_A: sideA,
    SIDE_B: sideB,
  };
  for (const k of Object.keys(vals)) {
    if (!template.includes(`{{${k}}}`)) {
      throw new Error(`prompt template: placeholder {{${k}}} missing`);
    }
  }
  // Function replacers: a `$` in the text must not act as a replacement pattern.
  return template.replace(
    /\{\{(RUBRIC|TASK_PROMPT|SIDE_A|SIDE_B)\}\}/g,
    (_, k: string) => vals[k]!,
  );
}

