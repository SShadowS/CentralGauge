async function readCache<T>(path: string): Promise<T | null> {
  let text: string;
  try {
    text = await Deno.readTextFile(path);
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) return null;
    throw e;
  }
  let v: Record<string, unknown>;
  try {
    v = JSON.parse(text);
  } catch {
    throw new Error(`cache file unreadable: ${path}`);
  }
  if (v["schema"] !== 1) throw new Error(`cache schema mismatch: ${path}`);
  const { schema: _s, ...rest } = v;
  return rest as T;
}

export interface Estimate {
  packets: number;
  calls: number;
  usd: number;
}
export function estimate(packets: Packet[], judges: Judge[]): Estimate {
  let calls = 0;
  let usd = 0;
  for (const p of packets) {
    for (const j of judges) {
      const ins = [p.text, p.swappedText, p.guessText];
      calls += ins.length;
      for (const t of ins) {
        usd += (t.length / 4) / 1e6 * j.usd_per_mtok_in +
          1500 / 1e6 * j.usd_per_mtok_out;
      }
    }
  }
  return { packets: packets.length, calls, usd };
}

/** The fixed system prompt of every judge call; part of every cache key. */
export const JUDGE_SYSTEM =
  "You are a code reviewer. Answer only with the JSON object the user message asks for.";

/**
 * Cache file name from the full request: system prompt, request prompt (for a
 * guess: the packet's guessText), judge identity and position.
 */
export async function cacheName(
  prompt: string,
  jkey: string,
  pos: string,
  system: string = JUDGE_SYSTEM,
): Promise<string> {
  return `${await sha256(`${system}\0${prompt}`)}-${jkey}-${pos}.json`;
}

export function formatEstimate(e: Estimate, skipped: number): string {
  return `${e.packets} packets, ${e.calls} calls, estimated cost $${
    e.usd.toFixed(2)
  } (estimate: excludes cache savings and retries; fixed 1500 output tokens per call; ${skipped} skipped)`;
}

export async function judgePackets(a: {
  packets: Packet[];
  judges: Judge[];
  out: string;
  template: string;
  rubric: string;
  client: JudgeClient;
  dryRun?: boolean;
}): Promise<{ cells: Cells; estimate: Estimate }> {
  const est = estimate(a.packets, a.judges);
  const cells: Cells = {};
  if (a.dryRun) return { cells, estimate: est };
  const dir = join(a.out, "cache");
  // One record per cell of this run (call made or cache hit), apart from cache/.
  const log = join(a.out, "cells.jsonl");
  await Deno.mkdir(a.out, { recursive: true });
  await Deno.writeTextFile(log, "");
  for (const j of a.judges) {
    const mine: Record<string, Cell> = cells[j.id] = {};
    const jkey =
      (await sha256(`${j.id}|${j.provider}|${j.model}|${j.thinking}`)).slice(
        0,
        12,
      );
    for (const p of a.packets) {
      const cell: Cell = mine[p.id] = {};
      const run = async <T extends { status: string; attempts: number }>(
        pos: string,
        prompt: string,
        parse: (t: string) => unknown,
        shape: (v: never, attempts: number) => T,
      ): Promise<T> => {
        const path = join(dir, await cacheName(prompt, jkey, pos));
        const record = (status: string, attempts: number, error?: string) =>
          Deno.writeTextFile(
            log,
            JSON.stringify({
              packet_id: p.id,
              judge: j.id,
              position: pos,
              status,
              attempts,
              ...(error === undefined ? {} : { error }),
            }) + "\n",
            { append: true },
          );
        const hit = await readCache<T>(path);
        if (hit) {
          const ok = (pos === "guess" ? OkGuess : OkVerdict).safeParse(hit);
          if (!ok.success) throw new Error(`cache payload invalid: ${path}`);
          await record("cached", ok.data.attempts);
          return ok.data as unknown as T;
        }
        const r = await callStrict(a.client, j, prompt, parse);
        if (!r.ok) {
          await record("failed", r.attempts, r.error);
          return {
            status: "failed",
            error: r.error,
            attempts: r.attempts,
          } as unknown as T;
        }
        const res = shape(r.value as never, r.attempts);
        await Deno.mkdir(dir, { recursive: true });
        await Deno.writeTextFile(path, JSON.stringify({ schema: 1, ...res }));
        await record("ok", r.attempts);
        return res;
      };
      const verdictShape = (verdicts: Verdicts, attempts: number) =>
        ({ status: "ok", verdicts, attempts }) as JudgeResult;
      cell.orig = await run(
        "orig",
        p.text,
        parseVerdict,
        verdictShape as never,
      );
      cell.swapped = await run(
        "swapped",
        p.swappedText,
        parseVerdict,
        verdictShape as never,
      );
      cell.guess = await run(
        "guess",
        p.guessText,
        parseGuess,
        ((guess: "A" | "B", attempts: number) => ({
          status: "ok",
          guess,
          attempts,
        })) as never,
      );
    }
  }
  return { cells, estimate: est };
}

// ------------------------------------------------------------ aggregation

export type ArmSpace = "variant" | "baseline" | "tie" | "missing";
const SPACES: ArmSpace[] = ["variant", "baseline", "tie", "missing"];

export function cohenKappa(pairs: [string, string][]): number | null {
  const n = pairs.length;
  if (n === 0) return null;
  const cats = [...new Set(pairs.flat())];
  const po = pairs.filter(([x, y]) => x === y).length / n;
  let pe = 0;
  for (const c of cats) {
    pe += pairs.filter(([x]) => x === c).length / n *
      (pairs.filter(([, y]) => y === c).length / n);
  }
  // pe == 1 (both judges constant on one category): kappa is undefined, never "perfect".
  return pe === 1 ? null : (po - pe) / (1 - pe);
}

/** Observed agreement po, reported next to kappa (which is undefined when pe == 1). */
export function agreementRate(pairs: [string, string][]): number | null {
  return pairs.length
    ? pairs.filter(([x, y]) => x === y).length / pairs.length
    : null;
}

function toArm(
  v: Verdict,
  pos: "orig" | "swapped",
  aRole: Key["a_role"],
): ArmSpace {
  if (v === "tie") return "tie";
  const orig = pos === "swapped" ? (v === "A" ? "B" : "A") : v;
  const other = aRole === "baseline" ? "variant" : "baseline";
  return orig === "A" ? aRole : other;
}

export interface PairMeta {
  id: string;
  task: string;
  repeat: number;
  key: Key;
  redactions?: { baseline: number; variant: number };
  baseline_id?: string | undefined;
  variant_id?: string | undefined;
}

export function aggregate(
  metas: PairMeta[],
  cells: Cells,
  judgeIds: string[],
  skipped: unknown[],
  campaignId?: string,
) {
  type Combo = { orig: ArmSpace; swapped: ArmSpace; combined: ArmSpace };
  const pairs = metas.map((m) => {
    const dimensions = {} as Record<Dimension, {
      judges: Record<string, Combo>;
      across: ArmSpace;
    }>;
    for (const d of DIMENSIONS) {
      const judges: Record<string, Combo> = {};
      for (const j of judgeIds) {
        const c = cells[j]?.[m.id];
        const at = (pos: "orig" | "swapped"): ArmSpace => {
          const r = c?.[pos];
          return r && r.status === "ok"
            ? toArm(r.verdicts[d].verdict, pos, m.key.a_role)
            : "missing";
        };
        const orig = at("orig");
        const swapped = at("swapped");
        judges[j] = {
          orig,
          swapped,
          combined: orig === "missing" || swapped === "missing"
            ? "missing"
            : orig === swapped
            ? orig
            : "tie",
        };
      }
      const votes = Object.values(judges).map((x) => x.combined).filter((
        x,
      ) => x !== "missing");
      let across: ArmSpace = votes.length ? "tie" : "missing";
      for (const s of ["variant", "baseline", "tie"] as const) {
        if (votes.filter((v) => v === s).length * 2 > votes.length) across = s;
      }
      dimensions[d] = { judges, across };
    }
    return {
      task: m.task,
      repeat: m.repeat,
      packet_id: m.id,
      baseline_id: m.baseline_id ?? null,
      variant_id: m.variant_id ?? null,
      redactions: m.redactions ?? { baseline: 0, variant: 0 },
      dimensions,
    };
  });

  const dims = {} as Record<Dimension, {
    counts: Record<ArmSpace, number>;
    kappa: Record<string, number | null>;
    agreement: Record<string, number | null>;
    swap_consistency: Record<string, number | null>;
  }>;
  for (const d of DIMENSIONS) {
    const counts = Object.fromEntries(SPACES.map((s) => [s, 0])) as Record<
      ArmSpace,
      number
    >;
    for (const p of pairs) counts[p.dimensions[d].across]++;
    const kappa: Record<string, number | null> = {};
    const agreement: Record<string, number | null> = {};
    for (let i = 0; i < judgeIds.length; i++) {
      for (let k = i + 1; k < judgeIds.length; k++) {
        const x = judgeIds[i]!;
        const y = judgeIds[k]!;
        const both: [string, string][] = [];
        for (const p of pairs) {
          const a = p.dimensions[d].judges[x]!.combined;
          const b = p.dimensions[d].judges[y]!.combined;
          if (a !== "missing" && b !== "missing") both.push([a, b]);
        }
        kappa[`${x}|${y}`] = cohenKappa(both);
        agreement[`${x}|${y}`] = agreementRate(both);
      }
    }
    const swap_consistency: Record<string, number | null> = {};
    for (const j of judgeIds) {
      const valid = pairs.map((p) => p.dimensions[d].judges[j]!).filter((c) =>
        c.orig !== "missing" && c.swapped !== "missing"
      );
      swap_consistency[j] = valid.length
        ? valid.filter((c) => c.orig === c.swapped).length / valid.length
        : null;
    }
    dims[d] = { counts, kappa, agreement, swap_consistency };
  }

  const guess_accuracy: Record<string, { correct: number; answered: number }> =
    {};
  const failures: Record<string, number> = {};
  for (const j of judgeIds) {
    let correct = 0;
    let answered = 0;
    let failed = 0;
    for (const m of metas) {
      const c = cells[j]?.[m.id];
      for (const r of [c?.orig, c?.swapped, c?.guess]) {
        if (r?.status === "failed") failed++;
      }
      if (c?.guess?.status === "ok") {
        answered++;
        const truth = m.key.a_role === "variant" ? "A" : "B";
        if (c.guess.guess === truth) correct++;
      }
    }
    guess_accuracy[j] = { correct, answered };
    failures[j] = failed;
  }
  return {
    pairs,
    summary: {
      campaign_id: campaignId ?? null,
      pairs: pairs.length,
      redaction_one_sided_share: pairs.length
        ? pairs.filter((p) =>
          (p.redactions.baseline > 0) !== (p.redactions.variant > 0)
        ).length / pairs.length
        : null,
      dimensions: dims,
      guess_accuracy,
      failures,
      skipped,
    },
  };
}

function csvEscape(s: string): string {
  return /[",\n]/.test(s) ? `"${s.replaceAll('"', '""')}"` : s;
}

export function toCsv(
  pairs: ReturnType<typeof aggregate>["pairs"],
  judgeIds: string[],
): string {
  const rows = [
    ["task", "repeat", "packet_id", "dimension", ...judgeIds, "across"],
  ];
  for (const p of pairs) {
    for (const d of DIMENSIONS) {
      const x = p.dimensions[d];
      rows.push([
        p.task,
        String(p.repeat),
        p.packet_id,
        d,
        ...judgeIds.map((j) => x.judges[j]!.combined),
        x.across,
      ]);
    }
  }
  return rows.map((r) => r.map(csvEscape).join(",")).join("\n") + "\n";
}

