/**
 * Deno.Command does not resolve `pi.cmd` through PATHEXT. On Windows an
 * extensionless name resolves through PATH to the first `<cmd>.exe`, then
 * `<cmd>.cmd`; anything else is used as given.
 */
export function resolveCommand(
  cmd: string,
  os: string = Deno.build.os,
  pathVar: string = Deno.env.get("PATH") ?? "",
): string {
  if (os !== "windows" || /\.[^\\/]+$/.test(cmd)) return cmd;
  for (const dir of pathVar.split(";").filter((d) => d !== "")) {
    for (const ext of [".exe", ".cmd"]) {
      const p = join(dir, cmd + ext);
      try {
        if (Deno.statSync(p).isFile) return p;
      } catch { /* not here */ }
    }
  }
  return cmd;
}

/**
 * pi argv for a judge call: no tools, extensions, MCP, skills, templates or
 * context files, and an explicit system prompt. The prompt goes on stdin.
 */
export function piArgs(
  req: { provider: string; model: string; thinking: string },
): string[] {
  return [
    "-p",
    "--no-session",
    "--no-tools",
    "--no-extensions",
    "--no-mcp",
    "--no-skills",
    "--no-prompt-templates",
    "--no-context-files",
    "--system-prompt",
    JUDGE_SYSTEM,
    "--provider",
    req.provider,
    "--model",
    req.model,
    "--thinking",
    req.thinking,
  ];
}

export interface PiRun {
  command: string;
  args: string[];
  cwd: string;
  stdin: string;
}
export type PiRunner = (r: PiRun) => Promise<
  { success: boolean; code: number; stdout: string; stderr: string }
>;

/**
 * A user or project SYSTEM.md / APPEND_SYSTEM.md would change the judge's
 * instructions behind the cache's back: refuse. stat only, nothing is read.
 */
export function assertNoSystemOverrides(agentDir: string, cwd: string): void {
  for (const dir of [agentDir, join(cwd, ".pi")]) {
    for (const name of ["SYSTEM.md", "APPEND_SYSTEM.md"]) {
      const p = join(dir, name);
      let found = true;
      try {
        Deno.statSync(p);
      } catch {
        found = false;
      }
      if (found) {
        throw new Error(
          `refusing to run the judge: ${p} would override its system prompt`,
        );
      }
    }
  }
}

function defaultAgentDir(): string {
  return Deno.env.get("PI_CODING_AGENT_DIR") ??
    join(
      Deno.env.get("USERPROFILE") ?? Deno.env.get("HOME") ?? ".",
      ".pi",
      "agent",
    );
}

/** The real spawn: 20-minute timeout with tree kill, prompt on stdin. */
export const spawnPi: PiRunner = async (r) => {
  const child = new Deno.Command(r.command, {
    args: r.args,
    cwd: r.cwd,
    stdin: "piped",
    stdout: "piped",
    stderr: "piped",
  }).spawn();
  let timedOut = false;
  const kill = async () => {
    if (Deno.build.os === "windows") {
      await new Deno.Command("taskkill", {
        args: ["/PID", String(child.pid), "/T", "/F"],
        stdout: "null",
        stderr: "null",
      }).output().catch(() => {});
    } else {
      try {
        child.kill("SIGKILL");
      } catch { /* already gone */ }
    }
  };
  const timer = setTimeout(async () => {
    timedOut = true;
    await kill();
  }, 20 * 60_000);
  try {
    // Prompt on stdin: the Windows pi.cmd shim truncates argv at the first newline.
    try {
      const w = child.stdin.getWriter();
      await w.write(enc.encode(r.stdin));
      await w.close();
    } catch (e) {
      // Never leave the process tree running behind a failed write.
      await kill();
      await child.output().catch(() => {});
      throw e;
    }
    const o = await child.output();
    if (timedOut) throw new Error("pi timed out after 20 min");
    const dec = new TextDecoder();
    return {
      success: o.success,
      code: o.code,
      stdout: dec.decode(o.stdout),
      stderr: dec.decode(o.stderr),
    };
  } finally {
    clearTimeout(timer);
  }
};

export function makePiClient(
  config: JudgeConfig,
  o: { run?: PiRunner; agentDir?: string } = {},
): JudgeClient {
  const run = o.run ?? spawnPi;
  return async (req) => {
    const cwd = await Deno.makeTempDir();
    try {
      assertNoSystemOverrides(o.agentDir ?? defaultAgentDir(), cwd);
      const r = await run({
        command: resolveCommand(config.pi_command),
        args: piArgs(req),
        cwd,
        stdin: req.prompt,
      });
      if (!r.success) {
        throw new Error(`pi exited ${r.code}: ${r.stderr.trim()}`);
      }
      return r.stdout;
    } finally {
      await Deno.remove(cwd, { recursive: true }).catch(() => {});
    }
  };
}

// ---------------------------------------------------------------- loading

type J = Record<string, unknown>;
const readJson = async (p: string): Promise<J> =>
  JSON.parse(await Deno.readTextFile(p)) as J;

export interface PairRef {
  task: string;
  repeat: number;
  baseline: string;
  variant: string;
  baseFinal: string;
  varFinal: string;
  baselineId: string;
  variantId: string;
}

export async function loadPairs(o: {
  results: string;
  campaign: string;
  pair: string[];
  task: string[];
}) {
  const campaign = await readJson(
    join(o.results, "campaigns", `${o.campaign}.json`),
  );
  const exp = campaign["experiment"] as {
    baseline: string;
    variants: string[];
  };
  const refapp = new Map(
    (campaign["task_set"] as { tasks: { id: string; refapp_commit: string }[] })
      .tasks.map((t) => [t.id, t.refapp_commit]),
  );
  const arms = o.pair.length
    ? o.pair.map((p) => {
      const parts = p.split(":");
      if (parts.length !== 2 || !parts[0] || !parts[1]) {
        throw new Error(`--pair needs base:variant, got "${p}"`);
      }
      return parts as [string, string];
    })
    : exp.variants.map((v) => [exp.baseline, v] as [string, string]);
  // Latest attempt per cell, as analyze-campaign does.
  const cells = new Map<string, J>();
  const manifests: unknown[] = [];
  // Through the store, so a re-derivation (R-10) is applied.
  for (const x of await new RecordStore(o.results).executions(o.campaign)) {
    const e = x as unknown as J;
    manifests.push(e["manifest"]);
    const key = `${e["arm"]}|${e["task_id"]}|${e["repeat"]}`;
    const prev = cells.get(key);
    if (!prev || (e["attempt"] as number) > (prev["attempt"] as number)) {
      cells.set(key, e);
    }
  }
  const pairs: PairRef[] = [];
  const skipped: {
    task: string;
    repeat: number;
    arm: string;
    reason: string;
  }[] = [];
  for (const [b, v] of arms) {
    for (const e of cells.values()) {
      if (e["arm"] !== b) continue;
      const task = e["task_id"] as string;
      const repeat = e["repeat"] as number;
      if (o.task.length && !o.task.includes(task)) continue;
      const other = cells.get(`${v}|${task}|${repeat}`);
      if (!other) {
        skipped.push({ task, repeat, arm: v, reason: "no execution" });
        continue;
      }
      const noHash = [e, other].filter((x) => !x["workspace_hash"]);
      if (noHash.length) {
        for (const x of noHash) {
          skipped.push({
            task,
            repeat,
            arm: x["arm"] as string,
            reason: "no workspace_hash",
          });
        }
        continue;
      }
      pairs.push({
        task,
        repeat,
        baseline: b,
        variant: v,
        baselineId: e["id"] as string,
        variantId: other["id"] as string,
        baseFinal: join(o.results, "workspaces", e["workspace_hash"] as string),
        varFinal: join(
          o.results,
          "workspaces",
          other["workspace_hash"] as string,
        ),
      });
    }
  }
  for (const [b, v] of arms) {
    for (const e of cells.values()) {
      if (e["arm"] !== v) continue;
      const task = e["task_id"] as string;
      const repeat = e["repeat"] as number;
      if (o.task.length && !o.task.includes(task)) continue;
      if (!cells.has(`${b}|${task}|${repeat}`)) {
        skipped.push({ task, repeat, arm: v, reason: "no baseline partner" });
      }
    }
  }
  pairs.sort((x, y) =>
    `${x.task}|${x.repeat}|${x.variant}`.localeCompare(
      `${y.task}|${y.repeat}|${y.variant}`,
    )
  );
  return {
    pairs,
    skipped,
    refapp,
    manifests,
    armNames: [exp.baseline, ...exp.variants],
  };
}

// -------------------------------------------------------------------- CLI

async function main() {
  await new Command()
    .name("judge-pairs")
    .description("Blinded pairwise LLM-judge of solution quality.")
    .option("--results <dir:string>", "results dir", { required: true })
    .option("--campaign <id:string>", "campaign id", { required: true })
    .option("--repo <dir:string>", "refapp repo", { required: true })
    .option("--rev <rev:string>", "task revision", { required: true })
    .option("--out <dir:string>", "output dir", { required: true })
    .option("--config <file:string>", "judges.json", { required: true })
    .option("--prompt <file:string>", "judge-prompt.md", { required: true })
    .option("--rubric <file:string>", "rubric.md", { required: true })
    .option("--pair <p:string>", "base:variant (repeatable)", { collect: true })
    .option("--task <id:string>", "task id (repeatable)", { collect: true })
    .option("--seed <s:string>", "A/B and shuffle seed", { default: "q01" })
    .option("--dry-run", "build packets, count calls, no model call")
    .action(async (o) => {
      const config = JudgeConfigSchema.parse(
        JSON.parse(await Deno.readTextFile(o.config)),
      );
      const template = await Deno.readTextFile(o.prompt);
      const rubric = extractRubric(await Deno.readTextFile(o.rubric));
      const loaded = await loadPairs({
        results: o.results,
        campaign: o.campaign,
        pair: o.pair ?? [],
        task: o.task ?? [],
      });
      const mt = manifestTerms(loaded.armNames, loaded.manifests);
      const startCache = join(o.out, ".start");
      const starts = new Map<string, Promise<string>>();
      const prompts = new Map<string, Promise<string>>();
      const packets: Packet[] = [];
      const sides = await assignBalanced(o.seed, loaded.pairs);
      for (const p of loaded.pairs) {
        if (!starts.has(p.task)) {
          starts.set(
            p.task,
            startingTree(
              o.repo,
              o.rev,
              p.task,
              loaded.refapp.get(p.task)!,
              startCache,
            )
              .then((s) => s.dir),
          );
          // After the start tree: both extract into .start/tasks (a concurrent
          // extract hits a Windows sharing violation).
          prompts.set(
            p.task,
            starts.get(p.task)!.then(() =>
              loadTaskAt(o.repo, p.task, o.rev, join(startCache, "tasks"))
            ).then((at) =>
              Deno.readTextFile(join(at.task.dir, at.task.task.prompt))
            ),
          );
        }
        packets.push(
          await buildPacket({
            seed: o.seed,
            task: p.task,
            repeat: p.repeat,
            baseline: p.baseline,
            variant: p.variant,
            baselineIsA: sides.get(pairKey(p))!,
            baselineId: p.baselineId,
            variantId: p.variantId,
            taskPrompt: await prompts.get(p.task)!,
            startDir: await starts.get(p.task)!,
            baseFinal: p.baseFinal,
            varFinal: p.varFinal,
            template,
            rubric,
            terms: mt.terms,
            arms: mt.arms,
          }),
        );
      }
      await writePackets(o.out, packets);
      const judges = config.judges;
      const r = await judgePackets({
        packets,
        judges,
        out: o.out,
        template,
        rubric,
        client: makePiClient(config),
        dryRun: !!o.dryRun,
      });
      console.log(
        `${colors.cyan("[Packets]")} ${
          formatEstimate(r.estimate, loaded.skipped.length)
        }`,
      );
      if (o.dryRun) return;
      const ids = judges.map((j) => j.id);
      const metas = packets.map((p) => ({
        id: p.id,
        task: p.task,
        repeat: p.repeat,
        key: p.key,
        redactions: p.redactions,
        baseline_id: p.key.baseline_id,
        variant_id: p.key.variant_id,
      }));
      const agg = aggregate(metas, r.cells, ids, loaded.skipped, o.campaign);
      await Deno.writeTextFile(
        join(o.out, "pairs.json"),
        JSON.stringify(agg.pairs, null, 2) + "\n",
      );
      await Deno.writeTextFile(
        join(o.out, "summary.json"),
        JSON.stringify(agg.summary, null, 2) + "\n",
      );
      await Deno.writeTextFile(join(o.out, "pairs.csv"), toCsv(agg.pairs, ids));
      console.log(
        `${colors.green("[OK]")} wrote pairs.json, summary.json, pairs.csv`,
      );
    })
    .parse(Deno.args);
}

if (import.meta.main) await main();
