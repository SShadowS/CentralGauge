export const FIXED_TERMS = [
  "claude",
  "anthropic",
  "subagent",
  "subagents",
  "sub-agent",
  "skill",
  "skills",
  "mcp",
  "codex",
  "copilot",
  "pi",
  "cursor",
  "gemini",
  "gpt",
  "AI-generated",
  "generated by",
];
const STOP = new Set([
  "skill",
  "skills",
  "readme",
  "index",
  "agents",
  "hooks",
  "plugins",
  "src",
]);

type Component = { path?: string; files?: { path: string }[] } | null;

/**
 * What identifies an arm. `arms` (arm names, config ids) are redacted everywhere
 * in a side's text; `terms` (the fixed tooling words, plus skill, subagent,
 * plugin and MCP names of 3+ chars from the manifests) only inside AL comments,
 * because code vocabulary ("Skill", "Cursor", the `al` LSP) cannot identify an arm.
 * ponytail: names come from the manifest's file lists; a name that appears only
 * in file content is not found.
 */
export function manifestTerms(
  arms: string[],
  manifests: unknown[],
): { arms: string[]; terms: string[] } {
  const armSet = new Set<string>(arms);
  const terms = new Set<string>(FIXED_TERMS);
  const add = (t: string) => {
    if (t.length >= 3) terms.add(t);
  };
  const stems = (p: string) => {
    for (const seg of p.split(/[\/]/)) {
      const stem = seg.replace(/\.[^.]*$/, "");
      if (!STOP.has(stem.toLowerCase())) add(stem);
    }
  };
  for (const m of manifests as Record<string, unknown>[]) {
    if (typeof m["config_id"] === "string") armSet.add(m["config_id"]);
    const comps = [
      m["instructions"],
      m["skills"],
      m["agents"],
      m["hooks"],
      ...(Array.isArray(m["plugins"]) ? m["plugins"] : []),
    ] as Component[];
    for (const c of comps) {
      if (!c) continue;
      if (c.path) stems(c.path);
      for (const f of c.files ?? []) stems(f.path);
    }
    for (const k of ["mcp", "lsp"]) {
      for (const s of (m[k] as { name?: string }[] | undefined) ?? []) {
        if (s.name) add(s.name);
      }
    }
  }
  return {
    arms: [...armSet].filter((t) => t.length > 0),
    terms: [...terms],
  };
}

function termRegex(terms: string[]): RegExp | null {
  const parts = [...new Set(terms)].sort((a, b) => b.length - a.length).map(
    (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
  );
  return parts.length
    ? new RegExp(
      `(?<![\\p{L}\\p{N}_])(?:${parts.join("|")})(?![\\p{L}\\p{N}_])`,
      "giu",
    )
    : null;
}

/**
 * Redacts one complete AL source with a small tokenizer, so state never leaks
 * between old and new text or between hunks. Tokens: 'strings' ('' escapes),
 * "identifiers" ("" escapes), `//` line comments, block comments (multi-line)
 * and code. Arm names go everywhere; `terms` only inside comment tokens. Only
 * matched words are replaced, so line count and newlines never change.
 */
export function redactSource(
  src: string,
  arms: string[],
  terms: string[],
): { text: string; count: number } {
  let count = 0;
  const sub = (re: RegExp | null) => (s: string) =>
    re ? s.replace(re, () => (count++, "[redacted]")) : s;
  const armR = sub(termRegex(arms));
  const termR = sub(termRegex(terms));
  const s = armR(src);
  let out = "";
  let i = 0;
  const quoted = (q: string) => {
    let j = i + 1;
    while (j < s.length && s[j] !== "\n") {
      if (s[j] === q) {
        if (s[j + 1] === q) j += 2;
        else {
          j++;
          break;
        }
      } else j++;
    }
    out += s.slice(i, j);
    i = j;
  };
  while (i < s.length) {
    const c = s[i]!;
    if (c === "'" || c === '"') quoted(c);
    else if (s.startsWith("//", i)) {
      const e = s.indexOf("\n", i);
      const j = e < 0 ? s.length : e;
      out += termR(s.slice(i, j));
      i = j;
    } else if (s.startsWith("/*", i)) {
      const e = s.indexOf("*/", i + 2);
      const j = e < 0 ? s.length : e + 2;
      out += termR(s.slice(i, j));
      i = j;
    } else {
      out += c;
      i++;
    }
  }
  return { text: out, count };
}

/** Path segments: arm names and terms alike (a file name can identify an arm). */
export function redactPath(
  rel: string,
  arms: string[],
  terms: string[],
): { text: string; count: number } {
  let count = 0;
  const re = termRegex([...arms, ...terms]);
  const text = re ? rel.replace(re, () => (count++, "[redacted]")) : rel;
  return { text, count };
}

