const TEXT_EXT = /\.(al|xlf|rdl|rdlc)$|(^|\/)app\.json$/i;

async function appFiles(root: string, apps: Set<string>): Promise<string[]> {
  const out: string[] = [];
  const walk = async (dir: string, rel: string) => {
    for await (const e of Deno.readDir(dir)) {
      if (e.name.startsWith(".")) continue;
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (rel === "" && !apps.has(e.name)) continue;
      if (isTaskBuildArtifact(r)) continue;
      if (e.isDirectory) await walk(join(dir, e.name), r);
      else if (
        e.isFile && rel !== "" && isSourceFile(e.name) && TEXT_EXT.test(r)
      ) {
        out.push(r);
      }
    }
  };
  await walk(root, "");
  return out;
}

async function readFormatted(
  root: string,
  rel: string,
): Promise<string | null> {
  try {
    return formatText(
      await Deno.readTextFile(join(root, ...rel.split("/"))),
    );
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) return null;
    throw e;
  }
}

async function fileDiff(
  scratch: string,
  rel: string,
  a: string | null,
  b: string | null,
): Promise<string> {
  const pa = join(scratch, "old");
  const pb = join(scratch, "new");
  await Deno.writeTextFile(pa, a ?? "");
  await Deno.writeTextFile(pb, b ?? "");
  const o = await new Deno.Command("git", {
    args: [
      "diff",
      "--no-index",
      "--no-color",
      "--ignore-cr-at-eol",
      "--",
      "old",
      "new",
    ],
    cwd: scratch,
    stdout: "piped",
    stderr: "piped",
  }).output();
  if (o.code !== 0 && o.code !== 1) {
    throw new Error(`git diff: ${new TextDecoder().decode(o.stderr)}`);
  }
  const patch = new TextDecoder().decode(o.stdout);
  const i = patch.indexOf("\n@@");
  return `--- ${a === null ? "/dev/null" : `a/${rel}`}\n+++ ${
    b === null ? "/dev/null" : `b/${rel}`
  }${i < 0 ? "\n" : patch.slice(i)}`;
}

/**
 * One side: production app diffs, then Test app diffs; blocks in a seeded
 * shuffled order. Every old and new source is redacted whole (redactSource)
 * before it is diffed; header paths are redacted per segment. `count` is the
 * net number of redactions the side's final text carries.
 */
export async function buildSide(
  startDir: string,
  finalDir: string,
  shuffleKey: string,
  red: { arms: string[]; terms: string[] } = { arms: [], terms: [] },
): Promise<{ text: string; count: number }> {
  const apps = new Set<string>();
  for await (const e of Deno.readDir(startDir)) {
    if (e.isDirectory && !e.name.startsWith(".")) apps.add(e.name);
  }
  const rels = [
    ...new Set([
      ...await appFiles(startDir, apps),
      ...await appFiles(finalDir, apps),
    ]),
  ];
  const ranked = await Promise.all(
    rels.map(async (r) => {
      const shown = redactPath(r, red.arms, red.terms);
      return {
        r,
        shown,
        test: r.split("/")[0] === TEST_APP,
        h: await sha256(`${shuffleKey}|${shown.text}`),
      };
    }),
  );
  ranked.sort((x, y) =>
    Number(x.test) - Number(y.test) || x.h.localeCompare(y.h)
  );
  const scratch = await Deno.makeTempDir();
  try {
    const blocks: string[] = [];
    let count = 0;
    for (const { r, shown } of ranked) {
      const a0 = await readFormatted(startDir, r);
      const b0 = await readFormatted(finalDir, r);
      const a = a0 === null ? null : redactSource(a0, red.arms, red.terms);
      const b = b0 === null ? null : redactSource(b0, red.arms, red.terms);
      if ((a?.text ?? null) === (b?.text ?? null)) continue;
      count += shown.count + Math.max(0, (b?.count ?? 0) - (a?.count ?? 0));
      blocks.push(
        await fileDiff(scratch, shown.text, a?.text ?? null, b?.text ?? null),
      );
    }
    return {
      text: blocks.length ? blocks.join("\n") : "(no changes)\n",
      count,
    };
  } finally {
    await Deno.remove(scratch, { recursive: true }).catch(() => {});
  }
}

