export const DIMENSIONS = [
  "correctness_risk",
  "conventions",
  "minimality",
  "test_value",
  "readability",
] as const;
export type Dimension = (typeof DIMENSIONS)[number];
export type Verdict = "A" | "B" | "tie";
export type Verdicts = Record<
  Dimension,
  { verdict: Verdict; reason: string; cite: string }
>;

const CITE = /^([AB]):([^:]+)(?::(-?\d+))?$/;
function validCite(c: string): boolean {
  if (c === "none") return true;
  const m = CITE.exec(c);
  return m !== null && m[2]!.trim() !== "" &&
    (m[3] === undefined || Number(m[3]) !== 0);
}
const Entry = z.strictObject({
  verdict: z.enum(["A", "B", "tie"]),
  reason: z.string().refine((s) => s.trim() !== "" && !/[\r\n]/.test(s)),
  cite: z.string().refine(
    validCite,
    "cite: none, or <A|B>:<path>[:<nonzero line>]",
  ),
}).refine((e) => (e.verdict === "tie") === (e.cite === "none"), {
  message: "a tie cites none, a side verdict cites a place",
});
const VerdictsSchema = z.strictObject(
  Object.fromEntries(DIMENSIONS.map((d) => [d, Entry])) as Record<
    Dimension,
    typeof Entry
  >,
);

/** Whole text must be the JSON object: no fence stripping, no substring search. */
export function parseVerdict(text: string): Verdicts {
  return VerdictsSchema.parse(JSON.parse(text.trim())) as Verdicts;
}
export function parseGuess(text: string): "A" | "B" {
  return z.strictObject({ guess: z.enum(["A", "B"]) }).parse(
    JSON.parse(text.trim()),
  ).guess;
}

