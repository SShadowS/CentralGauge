export interface Key {
  A: string;
  B: string;
  a_role: "baseline" | "variant";
  /** Execution record ids (provenance for later joins); never in a packet. */
  baseline_id?: string;
  variant_id?: string;
}
export interface Packet {
  id: string;
  /** sha256 of the packet text (the cache key part); `id` also covers the pair. */
  sha: string;
  text: string;
  swappedText: string;
  /** Arm-guess request over the orig A/B sides (guessPrompt); no rubric or verdict format. */
  guessText: string;
  task: string;
  repeat: number;
  key: Key;
  /** Redactions per arm role; goes to pairs.json, never into the packet. */
  redactions: { baseline: number; variant: number };
}
export interface PacketInput {
  seed: string;
  task: string;
  repeat: number;
  baseline: string;
  variant: string;
  taskPrompt: string;
  startDir: string;
  baseFinal: string;
  varFinal: string;
  template: string;
  rubric: string;
  /** Tooling words and manifest names: redacted inside AL comments only. */
  terms: string[];
  /** Side assignment from assignBalanced. */
  baselineIsA: boolean;
  baselineId?: string;
  variantId?: string;
  /** Arm and config names: redacted everywhere. */
  arms: string[];
}

export async function buildPacket(i: PacketInput): Promise<Packet> {
  const shuffle = `${i.seed}|${i.task}|${i.repeat}`;
  const red = { arms: i.arms, terms: i.terms };
  const base = await buildSide(i.startDir, i.baseFinal, shuffle, red);
  const vari = await buildSide(i.startDir, i.varFinal, shuffle, red);
  const aBase = i.baselineIsA;
  const [a, b] = aBase ? [base.text, vari.text] : [vari.text, base.text];
  const text = fillTemplate(i.template, i.rubric, i.taskPrompt, a, b);
  const sha = await sha256(text);
  const id = (await sha256(
    `${i.task}|${i.repeat}|${i.baseline}|${i.variant}|${text}`,
  )).slice(0, 16);
  return {
    id,
    sha,
    text,
    swappedText: fillTemplate(i.template, i.rubric, i.taskPrompt, b, a),
    guessText: guessPrompt(i.taskPrompt, a, b),
    task: i.task,
    repeat: i.repeat,
    key: {
      ...(aBase
        ? { A: i.baseline, B: i.variant, a_role: "baseline" as const }
        : { A: i.variant, B: i.baseline, a_role: "variant" as const }),
      ...(i.baselineId ? { baseline_id: i.baselineId } : {}),
      ...(i.variantId ? { variant_id: i.variantId } : {}),
    },
    redactions: { baseline: base.count, variant: vari.count },
  };
}

/** Packets go to <out>/packets; the key (arm names) to <out>/key, never inside packets. */
export async function writePackets(out: string, packets: Packet[]) {
  await Deno.mkdir(join(out, "packets"), { recursive: true });
  await Deno.mkdir(join(out, "key"), { recursive: true });
  const key: Record<string, Key> = {};
  for (const p of packets) {
    await Deno.writeTextFile(join(out, "packets", `${p.id}.md`), p.text);
    key[p.id] = p.key;
  }
  await Deno.writeTextFile(
    join(out, "key", "key.json"),
    JSON.stringify(key, null, 2) + "\n",
  );
}

